import React, { lazy, Suspense } from 'react';
import { createRoot } from 'react-dom/client';
import SocialUniverse from './social/SocialUniverse.tsx';
import './style.css';
import PublicAccess from './PublicAccess.tsx';
const WeatherLab=lazy(()=>import('./planet/WeatherLab.tsx'));
const weatherLab=new URLSearchParams(location.search).get('weather-lab')==='1';
const FractureStudy=lazy(()=>import('./planet/FractureStudy.tsx'));
const PlanetLab=lazy(()=>import('./planet/PlanetLab.tsx'));
const study=new URLSearchParams(location.search).get('fracture-study')==='1';
const lab=new URLSearchParams(location.search).get('planet-lab')==='1';
createRoot(document.getElementById('root')!).render(<React.StrictMode><Suspense fallback={null}>{weatherLab?<WeatherLab/>:lab?<PlanetLab/>:study?<FractureStudy/>:<SocialUniverse/>}</Suspense><PublicAccess/></React.StrictMode>);
